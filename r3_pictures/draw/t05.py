def nline(labels, jumps=None, hl=None, y=120):
    n = len(labels)
    labs = [str(l) for l in labels]
    # the biggest label size at which neighbours keep 4px apart and the end
    # labels keep 4px from the canvas edge (the ticks move in for wide ends)
    sz = 16
    while True:
        wid = [(lambda q: q[2] - q[0])(ink_box(l, sz)) if l else 0 for l in labs]
        x0 = max(14, 5 + wid[0] / 2)
        x1 = min(186, 195 - wid[-1] / 2)
        step = (x1 - x0) / (n - 1)
        if sz <= 6 or max(wid) <= step - 4:
            break
        sz *= .95
    o = S(100, y + 50, 90) + P(f'M{round(min(8, x0 - 6), 1)} {y} H{round(max(192, x1 + 6), 1)}', None, 5)
    items = []
    for i, l in enumerate(labs):
        x = round(x0 + i * step, 1)
        o += P(f'M{x} {y - 8} V{y + 8}', None, 4)
        if l != '':
            items.append((l, x, y + 34))
        if hl is not None and i == hl:
            o += C(x, y + 28, 15, '#FFE08A', 4)
    o += texts(items, sz)
    for a, b in (jumps or []):
        xa, xb = x0 + a * step, x0 + b * step
        o += P(f'M{xa:.0f} {y - 10} Q{(xa + xb) / 2:.0f} {y - 10 - step * .9 * (b - a) ** .5:.0f} {xb:.0f} {y - 10}', None, 4, f'stroke="{RED}"')
    return o

def track(nums, hl=None, gap_at=None, y=100):
    n = len(nums)
    # a long track (7 or more) wraps onto 2 rows so its numbers stay big
    rows = 2 if n >= 7 or (n >= 5 and max(len(str(v)) for v in nums) >= 3) else 1
    per = -(-n // rows)
    w = min(40, 184 / per)
    x0 = 100 - w * per / 2
    ys = [y] if rows == 1 else [y - w / 2 - 4, y + w / 2 + 4]
    o = S(100, ys[-1] + w / 2 + 14, 90)
    items = []
    for i, v in enumerate(nums):
        x = round(x0 + (i % per) * w, 1)
        yy = round(ys[i // per] - w / 2, 1)
        o += R(x, yy, round(w, 1), round(w, 1), '#FFE08A' if i == hl else TILES[i % 6], sw=4)
        if v != '':
            items.append((str(v), x, yy))
    pad = max(2, min(6, w * .12))
    sz = min(fit_size(str(v), w - 4 - 2 * pad, w - 4 - 2 * pad, w * .5) for v in nums if v != '')
    return o + ''.join(boxed([v], x, y0, w, w, sz, pad=pad, inset=2, size=sz) for v, x, y0 in items)

def grid(start, rows, cols, hl=()):
    o = S(100, 186, 90) + R(10, 10, 180, 170, WHITE, rx=6)
    cw, ch = 180 / cols, 170 / rows
    items = []
    for r in range(rows):
        for c in range(cols):
            v = start + r * cols + c
            if v in hl:
                o += R(round(10 + c * cw, 1), round(10 + r * ch, 1), round(cw, 1), round(ch, 1), '#FFE08A', sw=0)
            items.append((str(v), round(10 + (c + .5) * cw, 1), round(10 + (r + .66) * ch, 1)))
    o += ''.join(P(f'M{10 + c * cw:.0f} 10 V180', None, 2) for c in range(1, cols)) + ''.join(P(f'M10 {10 + r * ch:.0f} H190', None, 2) for r in range(1, rows))
    return o + texts(items, min(ch * .45, cw * .4), sw=2)

