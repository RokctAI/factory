def sh(kind, x, y, r, col):
    if kind == 'c':
        return C(x, y, r, col, 4)
    if kind == 's':
        return R(round(x - r, 1), round(y - r, 1), round(2 * r, 1), round(2 * r, 1), col, rx=3, sw=4)
    if kind == 't':
        return P(f'M{x} {y - r:.1f} L{x + r:.1f} {y + r * .8:.1f} L{x - r:.1f} {y + r * .8:.1f} Z', col, 4)
    if kind == 'star':
        return mini('star', x, y, r * 1.2, col)
    if kind == 'moon':
        return P(f'M{x + r * .3:.1f} {y - r:.1f} A{r} {r} 0 1 0 {x + r * .3:.1f} {y + r:.1f} A{r * .75:.1f} {r * .75:.1f} 0 1 1 {x + r * .3:.1f} {y - r:.1f} Z', col, 4)
    if kind == 'cyl':
        return R(round(x - r * .7, 1), round(y - r, 1), round(r * 1.4, 1), round(2 * r, 1), col, rx=4, sw=4) + E(x, round(y - r, 1), round(r * .7, 1), round(r * .25, 1), col, 4)
    if kind == '?':
        return R(round(x - r, 1), round(y - r, 1), round(2 * r, 1), round(2 * r, 1), WHITE, rx=4, sw=4, extra='stroke-dasharray="6 5"') + text('?', x, y + r * .4, r * 1.1)
    raise KeyError(kind)

def pat(items, y=100):
    n = len(items)
    gap = 184 / n
    o = S(100, y + 36, 90)
    for i, it in enumerate(items):
        k, col = it[0], it[1]
        r = it[2] if len(it) > 2 else min(16, gap * .38)
        o += sh(k, round(8 + gap * (i + .5), 1), y, r, col)
    return o

