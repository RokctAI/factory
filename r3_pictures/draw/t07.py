def sweets_on(plates, per, left=0):
    o = S(100, 176, 92)
    w = 184 / plates
    for p in range(plates):
        x = 8 + w * (p + .5)
        o += E(round(x, 1), 130, round(w * .44, 1), 14, WHITE)
        for j in range(per):
            o += mini('sweet', round(x - (min(per, 3) - 1) * 9 + (j % 3) * 18, 1), 124 - (j // 3) * 16, 6, [ROSE, BLUE, GOLD][j % 3])
    for j in range(left):
        o += mini('sweet', 100 + j * 20, 60, 8, GREEN)
    return o

