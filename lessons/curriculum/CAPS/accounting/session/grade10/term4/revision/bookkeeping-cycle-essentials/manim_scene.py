        b5_cr2 = Tex("Bank 1 000").scale(0.95).shift(band_shift(5) + DOWN * 0.1 + RIGHT * 2.2)
        self.play(Write(b5_cr1))
        self.wait(1.5)
        self.play(Write(b5_cr2))
        self.wait(2)
        b5_bal = MathTex(r"\text{Balance: } 2\,400 - 300 - 1\,000 = 1\,100").scale(1.0).shift(band_shift(5) + DOWN * 1.9)
        self.play(Write(b5_bal))
        self.play(Create(SurroundingRectangle(b5_bal, color=GREEN)))
        self.wait(2.5)
        b5_l1 = Tex("Mrs Dube's page says the same R1 100 — agreement").scale(0.9).shift(band_shift(5) + DOWN * 2.9)
        self.play(Write(b5_l1))
        self.wait(3)

        # --- Band 6 (subtopic_4): what the agreement catches
        self.next_band(6)
        b6_title = Tex("Two counts, facing each other").scale(1.2).shift(band_shift(6) + UP * 2.2)
        self.play(Write(b6_title))
        self.wait(2)
        b6_l1 = Tex("Control from journal TOTALS;").scale(1.0).shift(band_shift(6) + UP * 1.2)
