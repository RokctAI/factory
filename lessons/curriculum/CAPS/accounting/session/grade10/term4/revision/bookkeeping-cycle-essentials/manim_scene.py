        self.play(Write(b2_l6))
        self.wait(3)

        # --- Band 3 (subtopic_3): posting and balancing the ledger
        self.next_band(3)
        b3_title = Tex("Balancing the ledger").scale(1.2).shift(band_shift(3) + UP * 2.2)
        self.play(Write(b3_title))
