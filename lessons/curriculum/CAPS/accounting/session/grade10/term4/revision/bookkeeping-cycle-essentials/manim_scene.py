        self.wait(2)
        b7_l1 = Tex("The shoebox: till tapes, invoices, credit notes").scale(0.95).shift(band_shift(7) + UP * 1.2)
        self.play(Write(b7_l1))
        self.wait(2.5)
        b7_l2 = Tex("Two questions sort every slip:").scale(1.0).shift(band_shift(7) + UP * 0.3)
        b7_l3 = Tex("cash or promise? which way did value travel?").scale(1.0).shift(band_shift(7) + DOWN * 0.5)
        self.play(Write(b7_l2))
        self.play(Write(b7_l3))
        self.play(Create(SurroundingRectangle(b7_l3, color=GREEN)))
        self.wait(2.5)
        b7_l4 = Tex("Till tape R6 900 — cash in. Dube's invoice").scale(0.95).shift(band_shift(7) + DOWN * 1.5)
