        self.play(Write(b1_l1))
        self.wait(2)
        b1_l2 = Tex("Cash out — CPJ (EFT records)").scale(0.95).shift(band_shift(1) + UP * 0.5)
        self.play(Write(b1_l2))
        self.wait(2)
        b1_l3 = Tex("Credit sales — DJ (duplicate invoices);").scale(0.95).shift(band_shift(1) + DOWN * 0.2)
        b1_l4 = Tex("returns in — DAJ (credit notes)").scale(0.95).shift(band_shift(1) + DOWN * 0.9)
        self.play(Write(b1_l3))
        self.play(Write(b1_l4))
        self.wait(2.5)
        b1_l5 = Tex("Credit purchases — CJ; returns out — CAJ").scale(0.95).shift(band_shift(1) + DOWN * 1.7)
        self.play(Write(b1_l5))
        self.wait(2)
