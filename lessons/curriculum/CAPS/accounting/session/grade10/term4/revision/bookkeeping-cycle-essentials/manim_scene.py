        b0_l4 = Tex("Credit side: equity, liabilities, income increase").scale(0.95).shift(DOWN * 1.5)
        self.play(Write(b0_l3))
        self.play(Write(b0_l4))
        self.wait(2.5)
        b0_l5 = Tex("Capital deposit R10 000: debit Bank,").scale(0.95).shift(DOWN * 2.4)
        b0_l6 = Tex("credit Capital — the equation stays level").scale(0.95).shift(DOWN * 3.1)
        self.play(Write(b0_l5))
        self.play(Write(b0_l6))
        self.wait(3)

        # --- Band 1 (subtopic_2): six journals, six documents
        self.next_band(1)
