        self.wait(2)
        b6_l5 = Tex("Creditors mirror: 3 000 $-$ 2 000 = R1 000 both ways").scale(0.95).shift(band_shift(6) + DOWN * 2.2)
        self.play(Write(b6_l5))
        self.wait(2)
        b6_l6 = Tex("Internal control in miniature").scale(1.0).shift(band_shift(6) + DOWN * 3.0)
        self.play(Write(b6_l6))
        self.wait(3)

        # ============ Part 2 — Simplifier ============
        # --- Band 7 (subtopic_5): one slip, six boxes
        self.next_band(7)
