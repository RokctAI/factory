        self.wait(3)

        # --- Band 9 (subtopic_7): counting the street twice
        self.next_band(9)
        b9_title = Tex("Counting the street twice").scale(1.2).shift(band_shift(9) + UP * 2.2)
        self.play(Write(b9_title))
        self.wait(2)
        b9_l1 = Tex("Exercise book: a page per customer, slip by slip").scale(0.95).shift(band_shift(9) + UP * 1.2)
        self.play(Write(b9_l1))
        self.wait(2)
        b9_l2 = Tex("Main books: ONE total line, from journal totals").scale(0.95).shift(band_shift(9) + UP * 0.4)
        self.play(Write(b9_l2))
        self.wait(2.5)
        b9_l3 = Tex("Month-end: both counts say R1 100 — believable").scale(0.95).shift(band_shift(9) + DOWN * 0.5)
        self.play(Write(b9_l3))
