from manim import *

# Band-layout whiteboard scene for the CAPS Grade 10 Accounting session duo
# "Bookkeeping Cycle Essentials" (revision). Add-only lifecycle, one band per
# teaching beat, camera moves down between bands. Covers all seven subtopics:
# Part 1 Expert (subtopics 1-4), Part 2 Simplifier (subtopics 5-7) in fresh
# bands. subtopics.json durations 220/220/220/220/180/190/190 of 1440 s.
# The debtors control check is drawn as true T-account rails (Lines) with
# entries posted in script order and the balance boxed last.

BAND = config.frame_height


def band_shift(k):
    return DOWN * BAND * k


def strike(m):
    return Line(m.get_corner(DL) + 0.08 * DL, m.get_corner(UR) + 0.08 * UR,
                color=RED, stroke_width=6)


class BookkeepingCycleSession(MovingCameraScene):
    def next_band(self, k):
        self.play(self.camera.frame.animate.move_to(band_shift(k)), run_time=0.8)

    def construct(self):
        # Intro beat: topic held full-screen while intro.md audio plays.
        self.wait(14)

        # ============ Part 1 — Expert ============
        # --- Band 0 (subtopic_1): the equation and the compass
        title = Tex("The Bookkeeping Cycle").scale(1.3).to_edge(UP)
        self.play(Write(title))
        self.wait(2)
