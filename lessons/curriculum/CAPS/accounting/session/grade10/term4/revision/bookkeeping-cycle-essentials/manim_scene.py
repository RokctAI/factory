        self.play(Write(b8_l1))
        self.play(Write(b8_l2))
        self.wait(2.5)
        b8_l3 = MathTex(r"\text{The weigh-in: } 20\,000 = 20\,000").scale(1.1).shift(band_shift(8) + DOWN * 0.6)
        self.play(Write(b8_l3))
        self.play(Create(SurroundingRectangle(b8_l3, color=GREEN)))
        self.wait(2.5)
        b8_l4 = Tex("The scale cannot smell wrong pages or a").scale(0.95).shift(band_shift(8) + DOWN * 1.6)
        b8_l5 = Tex("stolen slip — the first guard, not the only one").scale(0.95).shift(band_shift(8) + DOWN * 2.4)
        self.play(Write(b8_l4))
