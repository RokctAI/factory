        self.play(Create(SurroundingRectangle(b10_l4, color=GREEN)))
        self.wait(2)
        b10_l5 = Tex("Salt AND water, every neutralisation —").scale(1.0).shift(band_shift(10) + DOWN * 2.5)
        b10_l6 = Tex("the fizz waits for the carbonate lessons").scale(1.0).shift(band_shift(10) + DOWN * 3.2)
        self.play(Write(b10_l5))
        self.wait(1.5)
        self.play(Write(b10_l6))
