        self.play(Write(b4_l4))
        self.wait(1.5)
        self.play(Write(b4_l4b))
        self.wait(2)
        b4_l5 = MathTex(r"SO_4^{2-} \text{ needs TWO: } H_2SO_4").scale(1.05).shift(band_shift(4) + DOWN * 2.4)
        self.play(Write(b4_l5))
        self.play(Create(SurroundingRectangle(b4_l5, color=GREEN)))
        self.wait(3)

        # --- Band 5 (subtopic_3): building the bases, spotting fakes ---
        self.next_band(5)
        b5_l1 = MathTex(r"Na^+ + OH^- \Rightarrow NaOH").scale(1.05).shift(band_shift(5) + UP * 2.2)
        b5_l2 = MathTex(r"2Na^+ + CO_3^{2-} \Rightarrow Na_2CO_3").scale(1.05).shift(band_shift(5) + UP * 1.3)
        b5_l3 = MathTex(r"Na^+ + HCO_3^- \Rightarrow NaHCO_3").scale(1.05).shift(band_shift(5) + UP * 0.4)
        self.play(Write(b5_l1))
        self.wait(2)
        self.play(Write(b5_l2))
        self.wait(2)
        self.play(Write(b5_l3))
        self.wait(2)
        b5_w1 = MathTex(r"NaCO_3").scale(1.1).shift(band_shift(5) + DOWN * 0.7 + LEFT * 2.5)
        b5_w2 = MathTex(r"H_2NO_3").scale(1.1).shift(band_shift(5) + DOWN * 0.7 + RIGHT * 2.5)
        self.play(Write(b5_w1))
        self.play(Create(strike(b5_w1)))
        self.wait(1.5)
        self.play(Write(b5_w2))
        self.play(Create(strike(b5_w2)))
        self.wait(2)
        b5_n = Tex("Charges don't total zero — fakes").scale(1.05).shift(band_shift(5) + DOWN * 1.7)
        self.play(Write(b5_n))
        self.wait(2)
        b5_n2 = Tex("Audit every formula: do charges cancel?").scale(1.0).shift(band_shift(5) + DOWN * 2.6)
        self.play(Write(b5_n2))
        self.wait(3)

        # --- Band 6 (subtopic_4): salt takes the acid's surname ---
        self.next_band(6)
        b6_t = Tex("Acid + base = salt + water").scale(1.2).shift(band_shift(6) + UP * 2.2)
        self.play(Write(b6_t))
        self.wait(2)
        b6_l1 = Tex("Positive ion from the BASE,").scale(1.0).shift(band_shift(6) + UP * 1.2)
        b6_l2 = Tex("negative ion from the ACID").scale(1.0).shift(band_shift(6) + UP * 0.5)
        self.play(Write(b6_l1))
        self.wait(1.5)
        self.play(Write(b6_l2))
        self.wait(2)
        b6_e1 = MathTex(r"NaOH + HCl \rightarrow NaCl + H_2O").scale(1.0).shift(band_shift(6) + DOWN * 0.5)
        b6_e2 = MathTex(r"KOH + HNO_3 \rightarrow KNO_3 + H_2O").scale(1.0).shift(band_shift(6) + DOWN * 1.4)
        b6_e3 = MathTex(r"2NaOH + H_2SO_4 \rightarrow Na_2SO_4 + 2H_2O").scale(0.95).shift(band_shift(6) + DOWN * 2.3)
        self.play(Write(b6_e1))
        self.wait(2)
        self.play(Write(b6_e2))
        self.wait(2)
        self.play(Write(b6_e3))
        self.wait(2)
        b6_n = Tex("Diprotic acid needs TWO hydroxides").scale(1.0).shift(band_shift(6) + DOWN * 3.2)
        self.play(Write(b6_n))
        self.wait(3)

        # --- Band 7 (subtopic_4): reading salts backwards ---
        self.next_band(7)
        b7_t = Tex("Backwards: read the salt apart").scale(1.15).shift(band_shift(7) + UP * 2.2)
        self.play(Write(b7_t))
        self.wait(2)
        b7_l1 = Tex("chloride — hydrochloric; nitrate — nitric;").scale(1.0).shift(band_shift(7) + UP * 1.2)
        b7_l2 = Tex("sulphate — sulphuric; ethanoate — ethanoic").scale(1.0).shift(band_shift(7) + UP * 0.4)
        self.play(Write(b7_l1))
        self.wait(2)
        self.play(Write(b7_l2))
        self.wait(2)
        b7_l3 = Tex("Prepare potassium sulphate?").scale(1.05).shift(band_shift(7) + DOWN * 0.6)
        b7_l4 = MathTex(r"KOH + H_2SO_4").scale(1.1).shift(band_shift(7) + DOWN * 1.5)
        self.play(Write(b7_l3))
        self.wait(2)
        self.play(Write(b7_l4))
        self.play(Create(SurroundingRectangle(b7_l4, color=GREEN)))
        self.wait(2)
        b7_l5 = Tex("Sodium ethanoate? NaOH + ethanoic acid").scale(1.0).shift(band_shift(7) + DOWN * 2.5)
        self.play(Write(b7_l5))
        self.wait(3)

        # ===== Part 2 — Simplifier =====
        # --- Band 8 (subtopic_5): tour of the house ---
        self.next_band(8)
        b8_t = Tex("A tour of the house in nine chemicals").scale(1.15).shift(band_shift(8) + UP * 2.2)
        self.play(Write(b8_t))
        self.wait(2)
        b8_l1 = Tex(r"Kitchen: vinegar $CH_3COOH$,").scale(1.0).shift(band_shift(8) + UP * 1.2)
        b8_l2 = Tex(r"baking soda $NaHCO_3$").scale(1.0).shift(band_shift(8) + UP * 0.5)
        self.play(Write(b8_l1))
        self.wait(1.5)
        self.play(Write(b8_l2))
        self.wait(2)
        b8_l3 = Tex(r"Laundry: washing soda $Na_2CO_3$;").scale(1.0).shift(band_shift(8) + DOWN * 0.4)
        b8_l4 = Tex(r"sink: drain cleaner $NaOH$; cleaner: $NH_3$").scale(0.95).shift(band_shift(8) + DOWN * 1.2)
        self.play(Write(b8_l3))
        self.wait(1.5)
        self.play(Write(b8_l4))
        self.wait(2)
        b8_l5 = Tex(r"Garage: pool acid $HCl$, battery $H_2SO_4$,").scale(0.95).shift(band_shift(8) + DOWN * 2.1)
        b8_l6 = Tex(r"fertiliser traces back to $HNO_3$").scale(1.0).shift(band_shift(8) + DOWN * 2.9)
        self.play(Write(b8_l5))
        self.wait(1.5)
        self.play(Write(b8_l6))
        self.wait(3)

        # --- Band 9 (subtopic_6): charges snap like magnets ---
        self.next_band(9)
        b9_t = Tex("Charges snap together like magnets").scale(1.15).shift(band_shift(9) + UP * 2.2)
        self.play(Write(b9_t))
        self.wait(2)
        b9_l1 = Tex("Single + meets single $-$: click, one-to-one").scale(1.0).shift(band_shift(9) + UP * 1.2)
        b9_l2 = MathTex(r"HCl, \; HNO_3, \; NaOH, \; KOH, \; NaHCO_3").scale(1.0).shift(band_shift(9) + UP * 0.3)
        self.play(Write(b9_l1))
        self.wait(2)
        self.play(Write(b9_l2))
        self.wait(2)
        b9_l3 = Tex("Double-strength minus needs TWO singles:").scale(1.0).shift(band_shift(9) + DOWN * 0.7)
