        self.play(Create(SurroundingRectangle(b9_l4, color=GREEN)))
        self.wait(2)
        b9_l5 = Tex("The subscript 2 IS the second magnet").scale(1.0).shift(band_shift(9) + DOWN * 2.6)
        self.play(Write(b9_l5))
        self.wait(3)

        # --- Band 10 (subtopic_7): salts as compound words ---
        self.next_band(10)
        b10_t = Tex("Read a salt like a compound word").scale(1.15).shift(band_shift(10) + UP * 2.2)
        self.play(Write(b10_t))
        self.wait(2)
        b10_l1 = Tex("First name from the base,").scale(1.05).shift(band_shift(10) + UP * 1.2)
        b10_l2 = Tex("surname from the acid").scale(1.05).shift(band_shift(10) + UP * 0.5)
        self.play(Write(b10_l1))
        self.wait(1.5)
        self.play(Write(b10_l2))
        self.wait(2)
        b10_l3 = Tex("Potassium nitrate: KOH and nitric acid").scale(1.0).shift(band_shift(10) + DOWN * 0.5)
        self.play(Write(b10_l3))
        self.wait(2)
        b10_l4 = MathTex(r"H^+ + OH^- \rightarrow H_2O").scale(1.1).shift(band_shift(10) + DOWN * 1.5)
