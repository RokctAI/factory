from manim import *

# Band-layout whiteboard scene for the common acids and bases session duo.
# Covers all seven subtopics (Part 1 Expert: 1-4, Part 2 Simplifier: 5-7),
# band time proportional to subtopics.json (225/230/235/240/200/195/200 of
# 1525 s). Add-only lifecycle; exporter-safe mobjects only.

BAND = config.frame_height


def band_shift(k):
    return DOWN * BAND * k


def strike(m):
    return Line(m.get_corner(DL) + 0.08 * DL, m.get_corner(UR) + 0.08 * UR,
                color=RED, stroke_width=6)


class CommonAcidsAndBasesSession(MovingCameraScene):
    def next_band(self, k):
        self.play(self.camera.frame.animate.move_to(band_shift(k)), run_time=0.8)

    def construct(self):
        self.wait(14)

        # ===== Part 1 — Expert =====
        # --- Band 0 (subtopic_1): the four acids, first two ---
        title = Tex("The Four Acids You Must Know").scale(1.25).to_edge(UP)
        self.play(Write(title))
        self.wait(2)
        b0_l1 = Tex(r"1. Hydrochloric acid: $HCl$").scale(1.1).shift(UP * 1.1)
        b0_l2 = Tex("stomach acid, pool acid").scale(0.95).shift(UP * 0.4)
        self.play(Write(b0_l1))
        self.wait(1.5)
        self.play(Write(b0_l2))
        self.wait(2)
        b0_l3 = Tex(r"2. Nitric acid: $HNO_3$").scale(1.1).shift(DOWN * 0.5)
        b0_l4 = Tex("the acid of fertiliser manufacture").scale(0.95).shift(DOWN * 1.2)
        self.play(Write(b0_l3))
        self.wait(1.5)
        self.play(Write(b0_l4))
        self.wait(2)
        b0_l5 = Tex("One hydrogen ion each: MONOPROTIC").scale(1.05).shift(DOWN * 2.2)
        self.play(Write(b0_l5))
        self.wait(3)

        # --- Band 1 (subtopic_1): sulphuric and ethanoic ---
        self.next_band(1)
        b1_l1 = Tex(r"3. Sulphuric acid: $H_2SO_4$").scale(1.1).shift(band_shift(1) + UP * 2.2)
        b1_l2 = Tex("car batteries; TWO hydrogens: DIPROTIC").scale(1.0).shift(band_shift(1) + UP * 1.4)
        self.play(Write(b1_l1))
        self.wait(1.5)
        self.play(Write(b1_l2))
        self.wait(2)
        b1_l3 = Tex(r"4. Ethanoic acid: $CH_3COOH$ (vinegar)").scale(1.1).shift(band_shift(1) + UP * 0.4)
        self.play(Write(b1_l3))
        self.wait(2)
        b1_l4 = Tex("Four H in the formula, only ONE acidic —").scale(1.0).shift(band_shift(1) + DOWN * 0.5)
        b1_l5 = Tex("the one at the end, on the oxygen").scale(1.0).shift(band_shift(1) + DOWN * 1.3)
        self.play(Write(b1_l4))
        self.wait(2)
        self.play(Write(b1_l5))
        self.wait(2)
        b1_l6 = Tex("Weak acid: releases it reluctantly —").scale(1.0).shift(band_shift(1) + DOWN * 2.2)
        b1_l7 = Tex("which is why you can put it on chips").scale(1.0).shift(band_shift(1) + DOWN * 2.9)
        self.play(Write(b1_l6))
        self.wait(1.5)
        self.play(Write(b1_l7))
        self.wait(3)

        # --- Band 2 (subtopic_2): bases one to three ---
        self.next_band(2)
        b2_t = Tex("The Five Bases You Must Know").scale(1.2).shift(band_shift(2) + UP * 2.2)
        self.play(Write(b2_t))
        self.wait(2)
        b2_l1 = Tex(r"1. Sodium hydroxide: $NaOH$ (caustic soda)").scale(1.0).shift(band_shift(2) + UP * 1.1)
        b2_l2 = Tex(r"2. Potassium hydroxide: $KOH$ — its twin").scale(1.0).shift(band_shift(2) + UP * 0.2)
        self.play(Write(b2_l1))
        self.wait(2)
        self.play(Write(b2_l2))
        self.wait(2)
        b2_l3 = Tex(r"3. Ammonia: $NH_3$ — the odd one out:").scale(1.0).shift(band_shift(2) + DOWN * 0.8)
        b2_l4 = Tex("no hydroxide, no oxygen, no metal,").scale(1.0).shift(band_shift(2) + DOWN * 1.6)
        b2_l5 = Tex("yet a base — it accepts hydrogen ions").scale(1.0).shift(band_shift(2) + DOWN * 2.4)
        self.play(Write(b2_l3))
        self.wait(1.5)
        self.play(Write(b2_l4))
        self.wait(1.5)
        self.play(Write(b2_l5))
        self.wait(3)

        # --- Band 3 (subtopic_2): the carbonate pair ---
        self.next_band(3)
        b3_t = Tex("The classic confusion: the carbonate pair").scale(1.1).shift(band_shift(3) + UP * 2.2)
        self.play(Write(b3_t))
        self.wait(2)
        b3_l1 = Tex(r"4. Sodium carbonate: $Na_2CO_3$").scale(1.05).shift(band_shift(3) + UP * 1.1)
        b3_l2 = Tex("washing soda — TWO Na, no H").scale(1.0).shift(band_shift(3) + UP * 0.3)
        self.play(Write(b3_l1))
        self.wait(2)
        self.play(Write(b3_l2))
        self.wait(2)
        b3_l3 = Tex(r"5. Sodium hydrogen carbonate: $NaHCO_3$").scale(1.05).shift(band_shift(3) + DOWN * 0.7)
        b3_l4 = Tex("baking soda — ONE Na, one H").scale(1.0).shift(band_shift(3) + DOWN * 1.5)
        self.play(Write(b3_l3))
        self.wait(2)
        self.play(Write(b3_l4))
        self.wait(2)
        b3_l5 = MathTex(r"NaOH, \; KOH, \; NH_3, \; Na_2CO_3, \; NaHCO_3").scale(1.0).shift(band_shift(3) + DOWN * 2.5)
        self.play(Write(b3_l5))
        self.play(Create(SurroundingRectangle(b3_l5, color=GREEN)))
        self.wait(3)

        # --- Band 4 (subtopic_3): the ions, and building the acids ---
        self.next_band(4)
        b4_t = Tex("Build formulae: charges total zero").scale(1.15).shift(band_shift(4) + UP * 2.2)
        self.play(Write(b4_t))
        self.wait(2)
        b4_l1 = MathTex(r"+: \; H^+, \; Na^+, \; K^+").scale(1.05).shift(band_shift(4) + UP * 1.2)
        b4_l2 = MathTex(r"-: \; Cl^-, \; NO_3^-, \; OH^-, \; HCO_3^-").scale(1.0).shift(band_shift(4) + UP * 0.4)
        b4_l3 = MathTex(r"2-: \; SO_4^{2-}, \; CO_3^{2-}").scale(1.05).shift(band_shift(4) + DOWN * 0.4)
        self.play(Write(b4_l1))
        self.wait(1.5)
        self.play(Write(b4_l2))
        self.wait(1.5)
        self.play(Write(b4_l3))
        self.wait(2)
        b4_l4 = MathTex(r"H^+ + Cl^- \Rightarrow HCl").scale(1.0).shift(band_shift(4) + DOWN * 1.3 + LEFT * 3.0)
