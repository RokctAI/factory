        b10_l3 = MathTex(r"9{,}8 \to 1{,}62 \to 3{,}7\ \text{N per kg}").scale(1.0).shift(band_shift(10) + DOWN * 0.6)
        lab = Tex("Earth, Moon, Mars").scale(0.85).shift(band_shift(10) + DOWN * 1.3)
