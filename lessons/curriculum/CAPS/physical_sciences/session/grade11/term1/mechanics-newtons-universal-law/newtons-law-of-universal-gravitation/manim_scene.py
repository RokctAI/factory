from manim import *

# Band-layout whiteboard scene for the Universal Gravitation session duo.
# Part 1 — Expert: subtopics 1-4; Part 2 — Simplifier: subtopics 5-7.
# Band dwell proportional to subtopics.json (225/215/240/230/180/180/195
# of 1465 s). Exporter-safe mobjects only; add-only lifecycle; camera bands.

BAND = config.frame_height


def band_shift(k):
    return DOWN * BAND * k


def strike(m):
    return Line(m.get_corner(DL) + 0.08 * DL, m.get_corner(UR) + 0.08 * UR,
                color=RED, stroke_width=6)


class UniversalGravitationSession(MovingCameraScene):
    def next_band(self, k):
        self.play(self.camera.frame.animate.move_to(band_shift(k)), run_time=0.8)

    def construct(self):
        # Intro beat: topic display while intro.md plays (~4-5% of scene).
        self.wait(14)

        # ===== Part 1 — Expert =====
        # --- Band 0 (subtopic_1): the law ---
        title = Tex("Newton's Law of Universal Gravitation").scale(1.15).to_edge(UP)
        self.play(Write(title))
        self.wait(2)
        b0_l1 = MathTex(r"F = \frac{G m_1 m_2}{d^2}").scale(1.4).shift(UP * 1.0)
        self.play(Write(b0_l1))
        self.play(Create(SurroundingRectangle(b0_l1, color=BLUE)))
        self.wait(2.5)
        b0_l2 = MathTex(r"G = 6{,}67 \times 10^{-11}\ \text{N m}^2\text{kg}^{-2}").scale(1.0).shift(DOWN * 0.4)
        self.play(Write(b0_l2))
        self.wait(2.5)
        b0_l3 = Tex("Always attractive; a third-law pair").scale(0.95).shift(DOWN * 1.4)
        self.play(Write(b0_l3))
        self.wait(2)
        b0_l4 = Tex("$d$ is between the CENTRES").scale(0.95).shift(DOWN * 2.3)
        self.play(Write(b0_l4))
        self.wait(2.5)

        # --- Band 1 (subtopic_1): the scale of the force ---
        self.next_band(1)
        b1_title = Tex("Two learners, 60 kg and 80 kg, 1 m apart").scale(1.0).shift(band_shift(1) + UP * 2.3)
        self.play(Write(b1_title))
        self.wait(1.5)
        b1_l1 = MathTex(r"F = \frac{6{,}67 \times 10^{-11} \times 60 \times 80}{1^2}").scale(1.0).shift(band_shift(1) + UP * 1.2)
        self.play(Write(b1_l1))
        self.wait(2.5)
        b1_l2 = MathTex(r"F \approx 3{,}2 \times 10^{-7}\ \text{N}").scale(1.05).shift(band_shift(1) + UP * 0.1)
        self.play(Write(b1_l2))
        self.play(Create(SurroundingRectangle(b1_l2, color=GREEN)))
        self.wait(2)
        b1_l3 = Tex("Far too small to feel").scale(0.95).shift(band_shift(1) + DOWN * 0.8)
        self.play(Write(b1_l3))
        self.wait(2)
        b1_l4 = Tex(r"Earth ($5{,}98 \times 10^{24}$ kg) on 70 kg:").scale(0.95).shift(band_shift(1) + DOWN * 1.7)
        self.play(Write(b1_l4))
        self.wait(2)
        b1_l5 = MathTex(r"F = 686\ \text{N} = mg \; \text{— weight IS this force}").scale(0.95).shift(band_shift(1) + DOWN * 2.7)
        self.play(Write(b1_l5))
        self.wait(2.5)

        # --- Band 2 (subtopic_2): the ratio rules ---
        self.next_band(2)
        b2_title = Tex("Inverse-square reasoning").scale(1.15).shift(band_shift(2) + UP * 2.3)
        self.play(Write(b2_title))
        self.wait(1.5)
        b2_l1 = Tex(r"Double one mass $\Rightarrow$ force $\times$ 2").scale(1.0).shift(band_shift(2) + UP * 1.3)
        self.play(Write(b2_l1))
        self.wait(2)
        b2_l2 = Tex(r"Double both masses $\Rightarrow$ force $\times$ 4").scale(1.0).shift(band_shift(2) + UP * 0.4)
        self.play(Write(b2_l2))
        self.wait(2)
        b2_l3 = Tex(r"Double the distance $\Rightarrow$ force $\div$ 4").scale(1.0).shift(band_shift(2) + DOWN * 0.5)
        self.play(Write(b2_l3))
        self.wait(2)
        b2_l4 = Tex(r"Triple the distance $\Rightarrow$ force $\div$ 9").scale(1.0).shift(band_shift(2) + DOWN * 1.4)
        self.play(Write(b2_l4))
        self.wait(2)
        b2_trap = Tex(r"distance doubles, force halves").scale(1.0).shift(band_shift(2) + DOWN * 2.4)
        self.play(Write(b2_trap))
        self.play(Create(strike(b2_trap)))
        self.wait(1.5)
        b2_l5 = Tex("Distance changes are ALWAYS squared").scale(0.95).shift(band_shift(2) + DOWN * 3.2)
        self.play(Write(b2_l5))
        self.wait(2.5)

        # --- Band 3 (subtopic_2): combined ratio, worked ---
        self.next_band(3)
        b3_title = Tex("One mass tripled, distance halved").scale(1.1).shift(band_shift(3) + UP * 2.2)
        self.play(Write(b3_title))
        self.wait(1.5)
        b3_l1 = MathTex(r"\text{masses: } \times 3, \quad \text{distance: } \times 2^2 = 4").scale(1.0).shift(band_shift(3) + UP * 1.1)
        self.play(Write(b3_l1))
        self.wait(2.5)
        b3_l2 = MathTex(r"F_{new} = 3 \times 4 \times F = 12F").scale(1.1).shift(band_shift(3) + UP * 0.0)
        self.play(Write(b3_l2))
        self.play(Create(SurroundingRectangle(b3_l2, color=GREEN)))
        self.wait(2.5)
        b3_l3 = Tex(r"With numbers: $F = 3{,}6 \times 10^{-7}$ N, distance doubled").scale(0.9).shift(band_shift(3) + DOWN * 1.2)
        self.play(Write(b3_l3))
        self.wait(2)
        b3_l4 = MathTex(r"F_{new} = \frac{3{,}6 \times 10^{-7}}{4} = 9 \times 10^{-8}\ \text{N}").scale(1.0).shift(band_shift(3) + DOWN * 2.2)
        self.play(Write(b3_l4))
        self.play(Create(SurroundingRectangle(b3_l4, color=GREEN)))
        self.wait(3)

        # --- Band 4 (subtopic_3): deriving g ---
        self.next_band(4)
        b4_title = Tex("Set the law equal to weight").scale(1.1).shift(band_shift(4) + UP * 2.3)
        self.play(Write(b4_title))
        self.wait(1.5)
        b4_l1 = MathTex(r"mg = \frac{G M m}{r^2}").scale(1.15).shift(band_shift(4) + UP * 1.2)
        self.play(Write(b4_l1))
        self.wait(2.5)
        b4_l2 = Tex("The small $m$ cancels:").scale(1.0).shift(band_shift(4) + UP * 0.2)
        self.play(Write(b4_l2))
        self.wait(1.5)
        b4_l3 = MathTex(r"g = \frac{G M}{r^2}").scale(1.3).shift(band_shift(4) + DOWN * 0.8)
        self.play(Write(b4_l3))
        self.play(Create(SurroundingRectangle(b4_l3, color=BLUE)))
        self.wait(2.5)
        b4_l4 = Tex("Every object at one place falls alike —").scale(0.95).shift(band_shift(4) + DOWN * 2.0)
