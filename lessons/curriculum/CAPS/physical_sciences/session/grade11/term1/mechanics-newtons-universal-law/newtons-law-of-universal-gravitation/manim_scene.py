        self.wait(2.5)
        b5_l2 = MathTex(r"g_{Earth} = 9{,}8\ \text{m/s}^2 \; \text{— derived!}").scale(1.05).shift(band_shift(5) + UP * 0.9)
        self.play(Write(b5_l2))
        self.play(Create(SurroundingRectangle(b5_l2, color=GREEN)))
        self.wait(2.5)
        b5_l3 = MathTex(r"g_{Moon} = 1{,}62\ \text{m/s}^2 \approx \tfrac{1}{6} g_{Earth}").scale(1.0).shift(band_shift(5) + DOWN * 0.3)
        self.play(Write(b5_l3))
        self.wait(2.5)
        b5_l4 = Tex(r"Satellite at 2 Earth radii from the centre:").scale(0.95).shift(band_shift(5) + DOWN * 1.4)
        b5_l5 = MathTex(r"g = \frac{9{,}8}{2^2} = 2{,}45\ \text{m/s}^2").scale(1.0).shift(band_shift(5) + DOWN * 2.4)
        self.play(Write(b5_l4))
        self.play(Write(b5_l5))
        self.wait(3)

        # --- Band 6 (subtopic_4): weight on other planets ---
        self.next_band(6)
        b6_title = Tex("Mass in kg, weight in N — never swap").scale(1.05).shift(band_shift(6) + UP * 2.3)
        self.play(Write(b6_title))
        self.wait(2)
        b6_l1 = MathTex(r"\text{Earth: } w = 70 \times 9{,}8 = 686\ \text{N}").scale(1.0).shift(band_shift(6) + UP * 1.3)
        self.play(Write(b6_l1))
        self.wait(2)
        b6_l2 = MathTex(r"\text{Moon: } w = 70 \times 1{,}62 = 113{,}4\ \text{N}").scale(1.0).shift(band_shift(6) + UP * 0.4)
        self.play(Write(b6_l2))
        self.wait(2)
        b6_l3 = MathTex(r"\text{Mars: } g = 3{,}7, \; w = 259\ \text{N}").scale(1.0).shift(band_shift(6) + DOWN * 0.5)
        self.play(Write(b6_l3))
        self.wait(2.5)
        b6_l4 = Tex("The mass never moved from 70 kg").scale(1.0).shift(band_shift(6) + DOWN * 1.6)
        self.play(Write(b6_l4))
        self.play(Create(SurroundingRectangle(b6_l4, color=GREEN)))
        self.wait(3)

        # --- Band 7 (subtopic_4): true weightlessness ---
        self.next_band(7)
        b7_title = Tex("Weightlessness, properly").scale(1.15).shift(band_shift(7) + UP * 2.3)
        self.play(Write(b7_title))
        self.wait(1.5)
        b7_l1 = MathTex(r"\text{At the ISS: } g \approx 9\ \text{m/s}^2 \; \text{— still there}").scale(0.95).shift(band_shift(7) + UP * 1.3)
        self.play(Write(b7_l1))
        self.wait(2.5)
        b7_l2 = Tex("The station is in continuous FREE FALL,").scale(0.95).shift(band_shift(7) + UP * 0.4)
        b7_l3 = Tex("moving sideways fast enough to keep missing").scale(0.95).shift(band_shift(7) + DOWN * 0.3)
        self.play(Write(b7_l2))
        self.play(Write(b7_l3))
        self.wait(2.5)
        b7_l4 = Tex("No support force $=$ the feeling of weightlessness").scale(0.95).shift(band_shift(7) + DOWN * 1.3)
        self.play(Write(b7_l4))
        self.wait(2.5)
        b7_l5 = Tex("Weightlessness is free fall, not no gravity").scale(0.95).shift(band_shift(7) + DOWN * 2.3)
        self.play(Write(b7_l5))
        self.play(Create(SurroundingRectangle(b7_l5, color=GREEN)))
        self.wait(3)

        # ===== Part 2 — Simplifier =====
        # --- Band 8 (subtopic_5): everything pulls on everything ---
        self.next_band(8)
        b8_title = Tex("Everything pulls on everything").scale(1.2).shift(band_shift(8) + UP * 2.3)
        self.play(Write(b8_title))
        self.wait(2)
        b8_l1 = Tex("You are pulling on your desk right now").scale(0.95).shift(band_shift(8) + UP * 1.3)
        self.play(Write(b8_l1))
        self.wait(2.5)
        b8_l2 = Tex(r"Two learners: $\approx$ a third of a millionth of a newton").scale(0.9).shift(band_shift(8) + UP * 0.4)
        self.play(Write(b8_l2))
        self.wait(2.5)
        b8_l3 = Tex("You only notice when a PLANET joins in").scale(0.95).shift(band_shift(8) + DOWN * 0.6)
        self.play(Write(b8_l3))
        self.wait(2.5)
        b8_l4 = Tex("Earth pulls you down 686 N;").scale(0.95).shift(band_shift(8) + DOWN * 1.6)
