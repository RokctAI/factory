        self.play(Write(b8_l4))
        self.play(Write(b8_l5))
        self.play(Create(SurroundingRectangle(b8_l5, color=GREEN)))
        self.wait(3)

        # --- Band 9 (subtopic_6): double the distance, quarter the pull ---
        self.next_band(9)
        b9_title = Tex("Double the distance, quarter the pull").scale(1.1).shift(band_shift(9) + UP * 2.3)
        self.play(Write(b9_title))
        self.wait(2)
        b9_l1 = Tex("Like torchlight on a wall: step back twice").scale(0.95).shift(band_shift(9) + UP * 1.3)
        b9_l2 = Tex("as far, each patch gets a quarter").scale(0.95).shift(band_shift(9) + UP * 0.6)
        self.play(Write(b9_l1))
        self.play(Write(b9_l2))
        self.wait(2.5)
        b9_l3 = Tex(r"Masses are simple: double $\Rightarrow$ double").scale(0.95).shift(band_shift(9) + DOWN * 0.4)
        self.play(Write(b9_l3))
        self.wait(2.5)
        b9_l4 = MathTex(r"\times 3 \text{ mass, } \times 2 \text{ distance: } \frac{3}{4}F").scale(1.0).shift(band_shift(9) + DOWN * 1.4)
        self.play(Write(b9_l4))
        self.play(Create(SurroundingRectangle(b9_l4, color=GREEN)))
        self.wait(2.5)
        b9_l5 = Tex("Distance always gets squared").scale(1.0).shift(band_shift(9) + DOWN * 2.5)
        self.play(Write(b9_l5))
        self.wait(3)

        # --- Band 10 (subtopic_7): same you, different weight ---
        self.next_band(10)
        b10_title = Tex("Same you, different weight").scale(1.2).shift(band_shift(10) + UP * 2.3)
        self.play(Write(b10_title))
        self.wait(2)
