        self.play(Write(title))
        self.wait(2)
        b0_def = Tex("Momentum $=$ mass $\\times$ velocity (a VECTOR)").scale(1.05).shift(UP * 1.2)
        b0_f = MathTex(r"p = mv \;\; [\text{kg·m·s}^{-1}]").scale(1.15).shift(UP * 0.3)
