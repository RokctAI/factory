        self.play(Write(b3_l2))
        self.wait(2)
        b3_l3 = Tex("Feed electrical energy in $\\rightarrow$ rotation out").scale(1.05).shift(band_shift(3) + DOWN * 0.7)
        b3_l4 = Tex("MOTOR").scale(1.1).shift(band_shift(3) + DOWN * 1.5)
        self.play(Write(b3_l3))
        self.play(Write(b3_l4))
        self.play(Create(SurroundingRectangle(VGroup(b3_l1, b3_l2, b3_l3, b3_l4), color=GREEN)))
        self.wait(2.5)
        b3_l5 = Tex("Fans, drills, pumps, EVs: coils in fields").scale(1.0).shift(band_shift(3) + DOWN * 2.7)
        self.play(Write(b3_l5))
        self.wait(3)

        # --- Band 4 (subtopic_3): why the grid chose AC
        self.next_band(4)
        b4_title = Tex("Why the grid chose AC").scale(1.2).shift(band_shift(4) + UP * 2.2)
        self.play(Write(b4_title))
        self.wait(1.5)
        b4_l1 = Tex("Transformers change AC voltage easily").scale(1.05).shift(band_shift(4) + UP * 1.2)
        self.play(Write(b4_l1))
        self.wait(2)
        b4_l2 = MathTex(r"P_{loss} = I^2R").scale(1.25).shift(band_shift(4) + UP * 0.2)
        self.play(Write(b4_l2))
