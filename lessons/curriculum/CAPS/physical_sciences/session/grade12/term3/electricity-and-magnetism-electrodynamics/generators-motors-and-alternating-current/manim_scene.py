        self.play(Write(b6_l4))
        self.wait(2)
        b6_l5 = Tex("220 V on the wall is an rms value").scale(1.05).shift(band_shift(6) + DOWN * 3.0)
        self.play(Write(b6_l5))
        self.wait(3)

