        self.wait(2)
        self.play(Write(b4_l4))
        self.wait(2)
        b4_l5 = Tex("Step up for the journey, down to 220 V").scale(1.05).shift(band_shift(4) + DOWN * 2.7)
        self.play(Write(b4_l5))
        self.wait(3)

        # --- Band 5 (subtopic_3): the AC wave against the DC line
        self.next_band(5)
        b5_title = Tex("The AC signal: 50 cycles per second").scale(1.15).shift(band_shift(5) + UP * 2.8)
        self.play(Write(b5_title))
        self.wait(1.5)
        ax_x = Arrow(band_shift(5) + LEFT * 4.2, band_shift(5) + RIGHT * 4.2, buff=0)
        ax_y = Arrow(band_shift(5) + LEFT * 4.0 + DOWN * 2.0, band_shift(5) + LEFT * 4.0 + UP * 2.2, buff=0)
        x_lab = Tex("t").scale(0.9).shift(band_shift(5) + RIGHT * 4.5 + DOWN * 0.4)
        y_lab = Tex("V").scale(0.9).shift(band_shift(5) + LEFT * 4.5 + UP * 1.9)
        self.play(Create(ax_x), Create(ax_y), Write(x_lab), Write(y_lab))
        self.wait(1.5)
        # one AC cycle as a 6-segment polyline
        wave = VGroup(
            Line(band_shift(5) + LEFT * 4.0, band_shift(5) + LEFT * 3.0 + UP * 1.4),
            Line(band_shift(5) + LEFT * 3.0 + UP * 1.4, band_shift(5) + LEFT * 2.0 + UP * 1.4),
            Line(band_shift(5) + LEFT * 2.0 + UP * 1.4, band_shift(5) + LEFT * 0.0),
            Line(band_shift(5) + LEFT * 0.0, band_shift(5) + RIGHT * 1.0 + DOWN * 1.4),
            Line(band_shift(5) + RIGHT * 1.0 + DOWN * 1.4, band_shift(5) + RIGHT * 2.0 + DOWN * 1.4),
            Line(band_shift(5) + RIGHT * 2.0 + DOWN * 1.4, band_shift(5) + RIGHT * 4.0),
        ).set_color(BLUE)
        self.play(Create(wave), run_time=2)
        vmax_lab = MathTex(r"+V_{max}").scale(0.9).shift(band_shift(5) + LEFT * 2.5 + UP * 2.0)
        vmin_lab = MathTex(r"-V_{max}").scale(0.9).shift(band_shift(5) + RIGHT * 1.5 + DOWN * 2.0)
        self.play(Write(vmax_lab), Write(vmin_lab))
        self.wait(2)
        dc = DashedLine(band_shift(5) + LEFT * 4.0 + UP * 0.8, band_shift(5) + RIGHT * 4.0 + UP * 0.8, color=YELLOW)
        dc_lab = Tex("DC: flat line").scale(0.9).shift(band_shift(5) + RIGHT * 2.6 + UP * 1.3)
        self.play(Create(dc), Write(dc_lab))
        self.wait(2)
        b5_l1 = Tex("Crossing zero $=$ current changing direction").scale(1.0).shift(band_shift(5) + DOWN * 2.9)
        self.play(Write(b5_l1))
        self.wait(3)

