from manim import *

# Band-layout whiteboard scene for "Generators, Motors and Alternating Current"
# (Part 1 — Expert subtopics 1-4, Part 2 — Simplifier subtopics 5-7).
# Exporter-safe mobjects only, write-only reveals, camera moves between bands.
# Band dwell time follows subtopics.json (235/240/240/235/190/195/195 of 1530).

BAND = config.frame_height


def band_shift(k):
    return DOWN * BAND * k


class GeneratorsMotorsACSession(MovingCameraScene):
    def next_band(self, k):
        self.play(self.camera.frame.animate.move_to(band_shift(k)), run_time=0.8)

    def construct(self):
        self.wait(14)

        # ============ Part 1 — Expert ============
        # --- Band 0 (subtopic_1): induction and the generator principle
        title = Tex("Generators, Motors and AC").scale(1.3).to_edge(UP)
        self.play(Write(title))
        self.wait(2)
        b0_l1 = Tex("Generator: mechanical $\\rightarrow$ electrical").scale(1.1).shift(UP * 1.2)
        self.play(Write(b0_l1))
        self.wait(2)
        b0_l2 = Tex("Electromagnetic induction:").scale(1.1).shift(UP * 0.3)
        b0_l3 = Tex("changing flux through a coil induces an emf").scale(1.05).shift(DOWN * 0.5)
        self.play(Write(b0_l2))
        self.play(Write(b0_l3))
        self.wait(2.5)
        b0_l4 = Tex("Spin the coil: flux rises and falls,").scale(1.05).shift(DOWN * 1.5)
        b0_l5 = Tex("emf reverses every half turn — AC out").scale(1.05).shift(DOWN * 2.3)
        self.play(Write(b0_l4))
        self.play(Write(b0_l5))
        self.wait(3)

        # --- Band 1 (subtopic_1): build the AC generator; rings decide AC or DC
        self.next_band(1)
        b1_title = Tex("Build the AC generator").scale(1.2).shift(band_shift(1) + UP * 2.9)
        self.play(Write(b1_title))
        self.wait(1.5)
        # magnet poles
        poleN = Rectangle(width=0.8, height=2.2).shift(band_shift(1) + LEFT * 3.0 + UP * 1.2)
        poleS = Rectangle(width=0.8, height=2.2).shift(band_shift(1) + RIGHT * 3.0 + UP * 1.2)
        labN = Tex("N").scale(1.0).shift(band_shift(1) + LEFT * 3.0 + UP * 1.2)
        labS = Tex("S").scale(1.0).shift(band_shift(1) + RIGHT * 3.0 + UP * 1.2)
        self.play(Create(poleN), Write(labN), Create(poleS), Write(labS))
        self.wait(1.5)
        # armature coil between the poles
        coil = Rectangle(width=2.6, height=1.4).shift(band_shift(1) + UP * 1.2)
        coil_lab = Tex("coil (armature)").scale(0.85).shift(band_shift(1) + UP * 2.4)
        self.play(Create(coil), Write(coil_lab))
        self.wait(1.5)
        # shaft down to two slip rings and brushes
        shaft = Line(band_shift(1) + UP * 0.5, band_shift(1) + DOWN * 0.4)
        ring1 = Circle(radius=0.22).shift(band_shift(1) + LEFT * 0.35 + DOWN * 0.75)
        ring2 = Circle(radius=0.22).shift(band_shift(1) + RIGHT * 0.35 + DOWN * 0.75)
        rings_lab = Tex("slip rings").scale(0.85).shift(band_shift(1) + LEFT * 2.4 + DOWN * 0.75)
        br1 = Rectangle(width=0.28, height=0.28).shift(band_shift(1) + LEFT * 0.35 + DOWN * 1.25)
        br2 = Rectangle(width=0.28, height=0.28).shift(band_shift(1) + RIGHT * 0.35 + DOWN * 1.25)
        br_lab = Tex("brushes").scale(0.85).shift(band_shift(1) + RIGHT * 2.3 + DOWN * 1.25)
        self.play(Create(shaft), Create(ring1), Create(ring2), Write(rings_lab))
        self.play(Create(br1), Create(br2), Write(br_lab))
        self.wait(2)
        b1_l1 = Tex("Slip rings: emf reverses each half turn — AC").scale(1.0).shift(band_shift(1) + DOWN * 2.0)
        self.play(Write(b1_l1))
        self.wait(2)
        b1_l2 = Tex("Split-ring commutator swaps on cue — DC").scale(1.0).shift(band_shift(1) + DOWN * 2.9)
        self.play(Write(b1_l2))
        self.play(Create(SurroundingRectangle(b1_l2, color=GREEN)))
        self.wait(3)

        # --- Band 2 (subtopic_2): the motor effect, forces on the coil
        self.next_band(2)
        b2_title = Tex("Motors and the motor effect").scale(1.2).shift(band_shift(2) + UP * 2.9)
        self.play(Write(b2_title))
        self.wait(1.5)
        b2_l1 = Tex("Current-carrying conductor in a field").scale(1.05).shift(band_shift(2) + UP * 2.1)
        b2_l2 = Tex("experiences a force").scale(1.05).shift(band_shift(2) + UP * 1.4)
        self.play(Write(b2_l1))
        self.play(Write(b2_l2))
        self.wait(2)
        # coil seen face-on, opposite forces on the two sides
        mcoil = Rectangle(width=3.0, height=1.2).shift(band_shift(2) + DOWN * 0.1)
        fL = Arrow(band_shift(2) + LEFT * 1.5 + DOWN * 0.1, band_shift(2) + LEFT * 1.5 + UP * 1.3, buff=0, color=YELLOW)
        fR = Arrow(band_shift(2) + RIGHT * 1.5 + DOWN * 0.1, band_shift(2) + RIGHT * 1.5 + DOWN * 1.5, buff=0, color=YELLOW)
        fL_lab = MathTex(r"F").scale(0.9).shift(band_shift(2) + LEFT * 2.0 + UP * 0.9)
        fR_lab = MathTex(r"F").scale(0.9).shift(band_shift(2) + RIGHT * 2.0 + DOWN * 1.1)
        self.play(Create(mcoil))
        self.play(Create(fL), Write(fL_lab))
        self.play(Create(fR), Write(fR_lab))
        self.wait(2)
        b2_l3 = Tex("Opposite currents, opposite forces: it turns").scale(1.0).shift(band_shift(2) + DOWN * 2.1)
        self.play(Write(b2_l3))
        self.wait(2)
        b2_l4 = Tex("Commutator flips current each half turn").scale(1.0).shift(band_shift(2) + DOWN * 2.9)
        self.play(Write(b2_l4))
        self.wait(3)

        # --- Band 3 (subtopic_2): one device, two energy directions
        self.next_band(3)
        b3_title = Tex("Same device, opposite directions").scale(1.2).shift(band_shift(3) + UP * 2.2)
