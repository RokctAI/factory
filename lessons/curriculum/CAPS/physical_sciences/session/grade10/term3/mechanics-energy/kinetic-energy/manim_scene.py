        b2_t = Tex("The commonest error, killed").scale(1.15).shift(band_shift(2) + UP * 2.2)
        self.play(Write(b2_t))
        self.wait(1.5)
        b2_trap = MathTex(r"E_k = \tfrac{1}{2} \times 1000 \times 20 = 10\,000\ \text{J}").scale(1.0).shift(band_shift(2) + UP * 1.1)
        self.play(Write(b2_trap))
        self.play(Create(strike(b2_trap)))
        self.wait(2)
        b2_1 = Tex("Twenty times too small — the square forgot").scale(0.95).shift(band_shift(2) + UP * 0.2)
        self.play(Write(b2_1))
        self.wait(2)
        b2_2 = Tex("Defence: $v^2 = 400$ as its OWN line first").scale(1.0).shift(band_shift(2) + DOWN * 0.7)
        self.play(Write(b2_2))
        self.play(Create(SurroundingRectangle(b2_2, color=GREEN)))
        self.wait(2)
        b2_3 = MathTex(r"\text{Units: kg·m}^2\text{·s}^{-2} = \text{J} \; \checkmark").scale(1.0).shift(band_shift(2) + DOWN * 1.7)
        self.play(Write(b2_3))
        self.wait(2)
