from manim import *

# Band-layout whiteboard scene for kinetic-energy (Part 1 Expert subtopics
# 1-4, Part 2 Simplifier subtopics 5-7). Exporter-safe mobjects only;
# add-only lifecycle; the 1000 kg car problem worked line by line with the
# script's exact numbers and units.
# Time apportioned to subtopics.json (225/235/240/245/180/175/175 of 1475 s).

BAND = config.frame_height


def band_shift(k):
    return DOWN * BAND * k


def strike(m):
    return Line(m.get_corner(DL) + 0.08 * DL, m.get_corner(UR) + 0.08 * UR,
                color=RED, stroke_width=6)


class KineticEnergySession(MovingCameraScene):
    def next_band(self, k):
        self.play(self.camera.frame.animate.move_to(band_shift(k)), run_time=0.8)

    def construct(self):
        # Intro beat: topic held full-screen while intro.md audio plays.
        self.wait(14)

        # ============ Part 1 — Expert ============
        # --- Band 0 (subtopic_1): energy carried by motion ---
        title = Tex("Kinetic Energy").scale(1.3).to_edge(UP)
        self.play(Write(title))
        self.wait(2)
        a1 = Tex("Energy an object carries because it MOVES").scale(1.0).shift(UP * 1.0)
        self.play(Write(a1))
        self.wait(2)
        a2 = MathTex(r"E_k = \tfrac{1}{2} m v^2").scale(1.3).shift(UP * 0.0)
        self.play(Write(a2))
        self.play(Create(SurroundingRectangle(a2, color=GREEN)))
        self.wait(2.5)
        a3 = Tex("Mass dial: plain — double $m$, double $E_k$").scale(0.95).shift(DOWN * 1.0)
        self.play(Write(a3))
        self.wait(2)
        a4 = Tex("Speed dial: SQUARED — double $v$, four times").scale(0.95).shift(DOWN * 1.8)
        self.play(Write(a4))
        self.wait(2)
        a5 = Tex("Scalar, never negative: squaring erases sign").scale(0.95).shift(DOWN * 2.7)
        self.play(Write(a5))
        self.wait(3)

        # --- Band 1 (subtopic_2): a tonne at twenty ---
        self.next_band(1)
