        self.wait(2)
        b8_1 = MathTex(r"20^2 = 400 \; \text{(square first, own line)}").scale(1.0).shift(band_shift(8) + UP * 1.1)
        self.play(Write(b8_1))
        self.wait(2.5)
        b8_2 = MathTex(r"\tfrac{1}{2} \times 1000 = 500").scale(1.0).shift(band_shift(8) + UP * 0.1)
        self.play(Write(b8_2))
        self.wait(2)
        b8_3 = MathTex(r"500 \times 400 = 200\,000\ \text{J}").scale(1.05).shift(band_shift(8) + DOWN * 0.9)
        self.play(Write(b8_3))
        self.play(Create(SurroundingRectangle(b8_3, color=GREEN)))
        self.wait(2.5)
        b8_4 = Tex("Brakes swallow it all as heat, every stop").scale(0.95).shift(band_shift(8) + DOWN * 1.9)
        self.play(Write(b8_4))
        self.wait(2)
        b8_5 = Tex("Forget the square: 10 000 J, 20$\\times$ too thin").scale(0.95).shift(band_shift(8) + DOWN * 2.8)
        self.play(Write(b8_5))
        self.wait(3)

        # --- Band 9 (subtopic_7): the quadratic surcharge ---
        self.next_band(9)
        b9_t = Tex("The quadratic surcharge").scale(1.2).shift(band_shift(9) + UP * 2.2)
        self.play(Write(b9_t))
        self.wait(2)
        b9_1 = MathTex(r"40^2 = 1600: \; 500 \times 1600 = 800\,000\ \text{J}").scale(0.95).shift(band_shift(9) + UP * 1.1)
        self.play(Write(b9_1))
        self.play(Create(SurroundingRectangle(b9_1, color=GREEN)))
        self.wait(2.5)
        b9_2 = Tex("Double the pace, four times the fortune").scale(1.0).shift(band_shift(9) + UP * 0.1)
        self.play(Write(b9_2))
        self.wait(2)
        b9_3 = Tex("100 to 120 adds more than 0 to 60").scale(1.0).shift(band_shift(9) + DOWN * 0.8)
        self.play(Write(b9_3))
