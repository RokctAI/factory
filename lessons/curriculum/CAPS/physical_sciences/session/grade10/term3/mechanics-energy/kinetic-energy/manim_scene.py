        for m in (b5_1, b5_2, b5_3, b5_4):
            self.play(Write(m))
            self.wait(1.8)
        b5_5 = Tex("Scale: hundreds for balls, $10^5$ for cars").scale(0.95).shift(band_shift(5) + DOWN * 2.3)
        self.play(Write(b5_5))
        self.wait(3)

        # --- Band 6 (subtopic_4): the remaining traps ---
        self.next_band(6)
        b6_t = Tex("The classic traps").scale(1.2).shift(band_shift(6) + UP * 2.2)
        self.play(Write(b6_t))
        self.wait(1.5)
        b6_trap = MathTex(r"72^2 \; \text{(squared in km/h!)}").scale(1.0).shift(band_shift(6) + UP * 1.1)
        self.play(Write(b6_trap))
        self.play(Create(strike(b6_trap)))
        self.wait(2)
        b6_1 = Tex("Convert first: wrong unit squares the error").scale(0.95).shift(band_shift(6) + UP * 0.2)
        self.play(Write(b6_1))
        self.wait(2)
        b6_2 = Tex("Never drop the half: it doubles every answer").scale(0.95).shift(band_shift(6) + DOWN * 0.7)
        self.play(Write(b6_2))
        self.wait(2)
        b6_3 = Tex("Negative direction still gives positive $E_k$").scale(0.95).shift(band_shift(6) + DOWN * 1.6)
        self.play(Write(b6_3))
        self.wait(2)
        b6_4 = Tex("Compare energies by squares, never speeds").scale(0.95).shift(band_shift(6) + DOWN * 2.5)
        self.play(Write(b6_4))
