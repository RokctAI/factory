        # ============ Part 2 — Simplifier ============
        # --- Band 7 (subtopic_5): the moving wallet ---
        self.next_band(7)
        b7_t = Tex("The moving wallet").scale(1.2).shift(band_shift(7) + UP * 2.2)
        self.play(Write(b7_t))
        self.wait(2)
        b7_1 = Tex("Motion = carrying cash; stopping = spending").scale(0.95).shift(band_shift(7) + UP * 1.1)
        self.play(Write(b7_1))
        self.wait(2)
        b7_2 = Tex("Soft hands spend gently; a wall spends instantly").scale(0.9).shift(band_shift(7) + UP * 0.2)
        self.play(Write(b7_2))
        self.wait(2)
        b7_3 = Tex("Mass dial: full taxi = double the empty one").scale(0.95).shift(band_shift(7) + DOWN * 0.7)
        self.play(Write(b7_3))
        self.wait(2)
        b7_4 = Tex("Speed dial multiplies by ITSELF: 2$\\times$ = 4$\\times$").scale(0.95).shift(band_shift(7) + DOWN * 1.6)
        self.play(Write(b7_4))
