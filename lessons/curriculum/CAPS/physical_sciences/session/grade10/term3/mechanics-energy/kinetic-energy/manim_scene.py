        b3_3 = MathTex(r"E_k = 500 \times 1600 = 800\,000\ \text{J}").scale(1.05).shift(band_shift(3) + DOWN * 0.9)
        self.play(Write(b3_3))
        self.play(Create(SurroundingRectangle(b3_3, color=GREEN)))
        self.wait(2.5)
        b3_4 = MathTex(r"\frac{800\,000}{200\,000} = 4: \; \text{double speed, FOUR}\times").scale(0.95).shift(band_shift(3) + DOWN * 1.9)
        self.play(Write(b3_4))
        self.wait(2)
        b3_5 = Tex("Triple the speed: nine times ($3^2$)").scale(1.0).shift(band_shift(3) + DOWN * 2.8)
        self.play(Write(b3_5))
        self.wait(3)

        # --- Band 4 (subtopic_3): the road consequences ---
        self.next_band(4)
        b4_t = Tex("The square on the road").scale(1.2).shift(band_shift(4) + UP * 2.2)
        self.play(Write(b4_t))
        self.wait(1.5)
        b4_1 = Tex("4$\\times$ energy: about 4$\\times$ braking distance").scale(1.0).shift(band_shift(4) + UP * 1.1)
        self.play(Write(b4_1))
