        self.play(Write(b1_t))
        self.wait(1.5)
        b1_1 = MathTex(r"m = 1000\ \text{kg}, \; v = 20\ \text{m·s}^{-1}\ (72\ \text{km/h})").scale(0.9).shift(band_shift(1) + UP * 1.2)
        self.play(Write(b1_1))
        self.wait(2)
        b1_2 = MathTex(r"v^2 = 20^2 = 400 \; \text{(square first!)}").scale(1.05).shift(band_shift(1) + UP * 0.2)
        self.play(Write(b1_2))
        self.wait(2)
        b1_3 = MathTex(r"\tfrac{1}{2} \times 1000 = 500").scale(1.05).shift(band_shift(1) + DOWN * 0.8)
        self.play(Write(b1_3))
        self.wait(2)
        b1_4 = MathTex(r"E_k = 500 \times 400 = 200\,000\ \text{J}").scale(1.1).shift(band_shift(1) + DOWN * 1.8)
        self.play(Write(b1_4))
        self.play(Create(SurroundingRectangle(b1_4, color=GREEN)))
        self.wait(2.5)
        b1_5 = Tex("= a 2 kg brick raised 10 km high").scale(0.95).shift(band_shift(1) + DOWN * 2.8)
        self.play(Write(b1_5))
        self.wait(3)

        # --- Band 2 (subtopic_2): the forgotten square ---
