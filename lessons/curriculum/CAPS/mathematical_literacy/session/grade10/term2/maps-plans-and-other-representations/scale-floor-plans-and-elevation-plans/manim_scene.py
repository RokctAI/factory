from manim import *

# BAND LAYOUT: sequential vertical bands, one frame-height each; the camera
# moves down between teaching steps and nothing is ever removed. Only
# exporter-supported mobjects (Tex/MathTex, Line/Arrow, Dot, Circle,
# Rectangle/SurroundingRectangle) with write-only reveals — no sub-part
# transforms. The floor plan and elevation are hand-built from Rectangles and
# Lines (no Arc: the door swing is shown as a straight leaf line).
#
# Mirrors script.md across the seven subtopics of the duo (Part 1 — Expert:
# subtopics 1-4; Part 2 — Simplifier: 5-7); band time proportional to
# subtopics.json.

BAND = config.frame_height


def band_shift(k):
    """World-space shift that places content in band k."""
    return DOWN * BAND * k


class ScaleFloorElevationPlansSession(MovingCameraScene):
    def next_band(self, k):
        self.play(self.camera.frame.animate.move_to(band_shift(k)), run_time=0.8)

    def construct(self):
        # Intro beat: topic full-screen while intro.md audio plays (~4-5%).
        self.wait(15)

        # ============ Part 1 — Expert ============
        # --- Band 0 (subtopic_1): the number scale ---
        title = Tex("Scale, Floor Plans and Elevation Plans").scale(1.1).to_edge(UP)
        self.play(Write(title))
        self.wait(2)
        l01 = Tex("Number scale 1 : 50 — same units both sides").scale(1.0).shift(UP * 1.3)
        self.play(Write(l01))
        self.wait(2)
        l02 = MathTex(r"1:50: \; 1 \text{ cm} = 50 \text{ cm} = 0{,}5 \text{ m}").scale(1.05).shift(UP * 0.4)
        l03 = MathTex(r"1:100: \; 1 \text{ cm} = 100 \text{ cm} = 1 \text{ m}").scale(1.05).shift(DOWN * 0.5)
        l04 = MathTex(r"1:2\,000\,000: \; 1 \text{ cm} = 20 \text{ km}").scale(1.05).shift(DOWN * 1.4)
        self.play(Write(l02))
        self.wait(2)
        self.play(Write(l03))
        self.wait(2)
        self.play(Write(l04))
        self.wait(2)
        l05 = Tex("Bigger second number = smaller drawing").scale(1.0).shift(DOWN * 2.5)
        self.play(Write(l05))
        self.wait(3)

        # --- Band 1 (subtopic_1): the bar scale and the photocopier ---
        self.next_band(1)
        b1_t = Tex("The bar scale: a ruler printed on the plan").scale(1.05).shift(band_shift(1) + UP * 2.2)
        self.play(Write(b1_t))
        self.wait(1.5)
        # Bar scale: 3 segments of 2 cm each, labelled 1 m apiece.
        bar = Rectangle(width=6.0, height=0.5).shift(band_shift(1) + UP * 1.0)
        d1 = Line(band_shift(1) + UP * 1.25 + LEFT * 1.0, band_shift(1) + UP * 0.75 + LEFT * 1.0)
        d2 = Line(band_shift(1) + UP * 1.25 + RIGHT * 1.0, band_shift(1) + UP * 0.75 + RIGHT * 1.0)
        self.play(Create(bar))
        self.play(Create(d1), Create(d2))
        m0 = MathTex("0").scale(0.8).shift(band_shift(1) + UP * 0.35 + LEFT * 3.0)
        m1 = MathTex(r"1\text{ m}").scale(0.8).shift(band_shift(1) + UP * 0.35 + LEFT * 1.0)
        m2 = MathTex(r"2\text{ m}").scale(0.8).shift(band_shift(1) + UP * 0.35 + RIGHT * 1.0)
        m3 = MathTex(r"3\text{ m}").scale(0.8).shift(band_shift(1) + UP * 0.35 + RIGHT * 3.0)
        self.play(Write(m0), Write(m1), Write(m2), Write(m3))
        self.wait(2)
        b1_l1 = Tex("Each 2 cm segment stands for 1 m — 1 : 50").scale(1.0).shift(band_shift(1) + DOWN * 0.6)
        self.play(Write(b1_l1))
        self.wait(2)
        b1_l2 = Tex("Photocopy at 80\\%: the ratio becomes a lie,").scale(1.0).shift(band_shift(1) + DOWN * 1.5)
        b1_l3 = Tex("but the bar shrinks with the page — still true").scale(1.0).shift(band_shift(1) + DOWN * 2.3)
        self.play(Write(b1_l2))
        self.wait(2)
        self.play(Write(b1_l3))
        self.play(Create(SurroundingRectangle(b1_l3, color=GREEN)))
        self.wait(3)

        # --- Band 2 (subtopic_2): ruler to reality and back ---
        self.next_band(2)
        b2_t = Tex("Plan to reality: multiply. Back: divide.").scale(1.1).shift(band_shift(2) + UP * 2.2)
        self.play(Write(b2_t))
        self.wait(1.5)
        b2_l1 = MathTex(r"8{,}4 \text{ cm} \times 50 = 420 \text{ cm} = 4{,}20 \text{ m}").scale(1.05).shift(band_shift(2) + UP * 1.1)
        self.play(Write(b2_l1))
        self.wait(2.5)
        b2_l2 = MathTex(r"6{,}0 \text{ cm} \times 50 = 300 \text{ cm} = 3{,}00 \text{ m}").scale(1.05).shift(band_shift(2) + UP * 0.2)
        self.play(Write(b2_l2))
        self.wait(2.5)
        b2_l3 = Tex("Stoep 5,5 m on a 1 : 100 plan:").scale(1.0).shift(band_shift(2) + DOWN * 0.8)
        b2_l4 = MathTex(r"5{,}5 \text{ m} = 550 \text{ cm}; \;\; 550 \div 100 = 5{,}5 \text{ cm}").scale(1.0).shift(band_shift(2) + DOWN * 1.7)
        self.play(Write(b2_l3))
        self.wait(2)
        self.play(Write(b2_l4))
        self.play(Create(SurroundingRectangle(b2_l4, color=GREEN)))
        b2_l5 = Tex("Convert units first, then apply the ratio").scale(0.95).shift(band_shift(2) + DOWN * 2.7)
        self.play(Write(b2_l5))
        self.wait(3)

        # --- Band 3 (subtopic_2): the quotation ---
        self.next_band(3)
        b3_t = Tex("Turning the room into a quotation").scale(1.1).shift(band_shift(3) + UP * 2.2)
        self.play(Write(b3_t))
        self.wait(1.5)
        b3_l1 = MathTex(r"\text{Carpet: } 4{,}20 \times 3{,}00 = 12{,}6 \text{ m}^2").scale(1.0).shift(band_shift(3) + UP * 1.2)
        b3_l2 = Tex("$12{,}6 \\times 189 =$ R2 381,40").scale(1.0).shift(band_shift(3) + UP * 0.4)
        self.play(Write(b3_l1))
        self.wait(2)
        self.play(Write(b3_l2))
        self.wait(2)
        b3_l3 = MathTex(r"\text{Skirting: } 2(4{,}20 + 3{,}00) - 0{,}9 = 13{,}5 \text{ m}").scale(0.95).shift(band_shift(3) + DOWN * 0.5)
        b3_l4 = Tex("$13{,}5 \\times$ R42,00 = R567,00").scale(1.0).shift(band_shift(3) + DOWN * 1.3)
        self.play(Write(b3_l3))
        self.wait(2.5)
        self.play(Write(b3_l4))
        self.wait(2)
        b3_l5 = MathTex(r"\text{Paving: } 11 \div 0{,}02 = 550; \; \times 1{,}05 \to 578").scale(0.95).shift(band_shift(3) + DOWN * 2.2)
        self.play(Write(b3_l5))
        self.play(Create(SurroundingRectangle(b3_l5, color=GREEN)))
        b3_l6 = Tex("Materials always round UP").scale(0.95).shift(band_shift(3) + DOWN * 3.1)
        self.play(Write(b3_l6))
        self.wait(3)

        # --- Band 4 (subtopic_3): reading a floor plan ---
        self.next_band(4)
        b4_t = Tex("The floor plan: roof lifted off").scale(1.1).shift(band_shift(4) + UP * 2.2)
        self.play(Write(b4_t))
        self.wait(1.5)
        # Room outline with a door gap on the bottom wall and window on top.
        c = band_shift(4) + DOWN * 0.8 + LEFT * 2.2
        w_top = Line(c + LEFT * 2.1 + UP * 1.5, c + RIGHT * 2.1 + UP * 1.5)
        w_left = Line(c + LEFT * 2.1 + UP * 1.5, c + LEFT * 2.1 + DOWN * 1.5)
