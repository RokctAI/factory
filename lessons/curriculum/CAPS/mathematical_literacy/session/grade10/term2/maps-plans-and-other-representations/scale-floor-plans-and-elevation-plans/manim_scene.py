        self.play(Create(w_bot1), Create(w_bot2))
        leaf = Line(c + LEFT * 0.3 + DOWN * 1.5, c + LEFT * 0.3 + DOWN * 0.3)
        self.play(Create(leaf))
        door_lab = Tex("door + swing").scale(0.7).shift(c + DOWN * 2.0 + RIGHT * 0.3)
        self.play(Write(door_lab))
        win = Line(c + LEFT * 0.6 + UP * 1.62, c + RIGHT * 0.6 + UP * 1.62)
        win2 = Line(c + LEFT * 0.6 + UP * 1.38, c + RIGHT * 0.6 + UP * 1.38)
        win_lab = Tex("window").scale(0.7).shift(c + UP * 2.0)
        self.play(Create(win), Create(win2), Write(win_lab))
        bed = Tex("BED").scale(0.8).shift(c)
        self.play(Write(bed))
        self.wait(2)
        b4_l1 = Tex("Dimensions in mm: 4 200 = 4,2 m").scale(0.95).shift(band_shift(4) + UP * 1.0 + RIGHT * 3.0)
        b4_l2 = Tex("Arc shows the door swing").scale(0.95).shift(band_shift(4) + UP * 0.1 + RIGHT * 3.0)
        b4_l3 = Tex("North arrow = sun and weather").scale(0.95).shift(band_shift(4) + DOWN * 0.8 + RIGHT * 3.0)
        self.play(Write(b4_l1))
        self.wait(2)
        self.play(Write(b4_l2))
        self.wait(2)
        self.play(Write(b4_l3))
        self.wait(2)
        b4_l4 = Tex("Analyse like a family: propose the fix").scale(0.95).shift(band_shift(4) + DOWN * 3.2)
        self.play(Write(b4_l4))
        self.wait(3)

        # --- Band 5 (subtopic_4): the elevation ---
        self.next_band(5)
        b5_t = Tex("The elevation: standing straight in front").scale(1.05).shift(band_shift(5) + UP * 2.2)
        self.play(Write(b5_t))
        self.wait(1.5)
        e = band_shift(5) + DOWN * 1.0 + LEFT * 2.4
        wall = Rectangle(width=4.0, height=2.4).shift(e)
        self.play(Create(wall))
        roof = Line(e + LEFT * 2.0 + UP * 1.2, e + RIGHT * 2.0 + UP * 1.8)
        self.play(Create(roof))
        winr = Rectangle(width=1.2, height=1.2).shift(e + RIGHT * 0.9 + DOWN * 0.0 + UP * 0.3)
        self.play(Create(winr))
        h1 = Tex("wall 2,4 m").scale(0.75).shift(e + LEFT * 2.9 + UP * 0.0)
        h2 = Tex("sill 0,9 m").scale(0.75).shift(e + RIGHT * 0.9 + DOWN * 1.0)
        h3 = Tex("head at 2,1 m").scale(0.75).shift(e + RIGHT * 0.9 + UP * 1.25)
        self.play(Write(h1))
        self.wait(1.5)
        self.play(Write(h2), Write(h3))
        self.wait(2)
        b5_l1 = Tex("Named by the direction the wall FACES").scale(0.95).shift(band_shift(5) + UP * 1.1 + RIGHT * 2.6)
        self.play(Write(b5_l1))
        self.wait(2)
        b5_l2 = Tex("Elevation: heights, roof slope").scale(0.95).shift(band_shift(5) + UP * 0.2 + RIGHT * 2.9)
        b5_l3 = Tex("Floor plan: layout, areas").scale(0.95).shift(band_shift(5) + DOWN * 0.6 + RIGHT * 3.0)
        self.play(Write(b5_l2))
        self.play(Write(b5_l3))
        self.wait(3)

        # --- Band 6 (subtopic_4): combining the two drawings ---
        self.next_band(6)
        b6_t = Tex("Combine the drawings: wall area to paint").scale(1.05).shift(band_shift(6) + UP * 2.2)
        self.play(Write(b6_t))
        self.wait(1.5)
        b6_l1 = MathTex(r"\text{Plan gives } 14{,}4 \text{ m; elevation gives } 2{,}4 \text{ m}").scale(0.95).shift(band_shift(6) + UP * 1.2)
        b6_l2 = MathTex(r"14{,}4 \times 2{,}4 = 34{,}56 \text{ m}^2").scale(1.05).shift(band_shift(6) + UP * 0.3)
        self.play(Write(b6_l1))
        self.wait(2.5)
        self.play(Write(b6_l2))
        self.wait(2)
        b6_l3 = MathTex(r"\text{Door: } 0{,}9 \times 2{,}1 = 1{,}89 \text{ m}^2").scale(1.0).shift(band_shift(6) + DOWN * 0.6)
        b6_l4 = MathTex(r"\text{Window: } 1{,}2 \times 1{,}2 = 1{,}44 \text{ m}^2").scale(1.0).shift(band_shift(6) + DOWN * 1.5)
        self.play(Write(b6_l3))
        self.wait(2)
        self.play(Write(b6_l4))
        self.wait(2)
        b6_l5 = MathTex(r"34{,}56 - 1{,}89 - 1{,}44 = 31{,}23 \text{ m}^2").scale(1.05).shift(band_shift(6) + DOWN * 2.4)
        self.play(Write(b6_l5))
        self.play(Create(SurroundingRectangle(b6_l5, color=GREEN)))
        self.wait(3)

        # ============ Part 2 — Simplifier ============
        # --- Band 7 (subtopic_5): the shrunk house ---
        self.next_band(7)
        b7_t = Tex("The shrunk house").scale(1.2).shift(band_shift(7) + UP * 2.2)
        self.play(Write(b7_t))
        self.wait(2)
        b7_l1 = Tex("1 : 50 = fifty times smaller").scale(1.05).shift(band_shift(7) + UP * 1.2)
        self.play(Write(b7_l1))
        self.wait(2)
        b7_l2 = MathTex(r"\text{Page to reality: } 8{,}4 \times 50 = 420 \text{ cm}").scale(1.0).shift(band_shift(7) + UP * 0.3)
        self.play(Write(b7_l2))
        self.wait(2)
        b7_l3 = MathTex(r"\text{Reality to page: } 550 \div 100 = 5{,}5 \text{ cm}").scale(1.0).shift(band_shift(7) + DOWN * 0.6)
        self.play(Write(b7_l3))
        self.play(Create(SurroundingRectangle(b7_l3, color=GREEN)))
        self.wait(2.5)
        b7_l4 = Tex("The photocopier doesn't know ratios —").scale(1.0).shift(band_shift(7) + DOWN * 1.6)
        b7_l5 = Tex("the printed ruler shrinks too, so trust it").scale(1.0).shift(band_shift(7) + DOWN * 2.4)
        self.play(Write(b7_l4))
        self.play(Write(b7_l5))
        self.wait(3)

        # --- Band 8 (subtopic_6): bird's eye vs standing in front ---
        self.next_band(8)
        b8_t = Tex("Bird's eye and standing-in-front").scale(1.1).shift(band_shift(8) + UP * 2.2)
        self.play(Write(b8_t))
        self.wait(2)
        b8_l1 = Tex("Floor plan: roof off, looking down —").scale(1.0).shift(band_shift(8) + UP * 1.2)
        b8_l2 = Tex("answers ``where is everything?''").scale(1.0).shift(band_shift(8) + UP * 0.4)
        self.play(Write(b8_l1))
        self.play(Write(b8_l2))
        self.wait(2.5)
        b8_l3 = Tex("Elevation: one wall, straight on —").scale(1.0).shift(band_shift(8) + DOWN * 0.5)
        b8_l4 = Tex("answers ``how high?''").scale(1.0).shift(band_shift(8) + DOWN * 1.3)
        self.play(Write(b8_l3))
        self.play(Write(b8_l4))
        self.wait(2.5)
        b8_l5 = Tex("4 200 on a plan means millimetres: 4,2 m").scale(0.95).shift(band_shift(8) + DOWN * 2.2)
        self.play(Write(b8_l5))
        self.play(Create(SurroundingRectangle(b8_l5, color=GREEN)))
        self.wait(3)

        # --- Band 9 (subtopic_7): the shopping list ---
        self.next_band(9)
        b9_t = Tex("Turning the plan into a shopping list").scale(1.05).shift(band_shift(9) + UP * 2.2)
        self.play(Write(b9_t))
        self.wait(2)
        b9_l1 = Tex("Floor: 12,6 m$^2$ carpet — R2 381,40").scale(1.0).shift(band_shift(9) + UP * 1.2)
        self.play(Write(b9_l1))
        self.wait(2)
        b9_l2 = Tex("Edge: 14,4 $-$ 0,9 = 13,5 m — R567,00").scale(1.0).shift(band_shift(9) + UP * 0.3)
        self.play(Write(b9_l2))
        self.wait(2)
        b9_l3 = Tex("Stoep: 550 blocks + 5\\% = 578 blocks").scale(1.0).shift(band_shift(9) + DOWN * 0.6)
